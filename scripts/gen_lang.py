#!/usr/bin/env python3
"""Single source of truth for translation keys.

app/lang/keys.json is the canonical list of keys. This script:
  1. generates src/lang_keys.h  (S_* enum + g_tr_keys[] used by overlay_ui.c)
  2. makes sure app/lang/{es,en,pt}.json contain every key (keeps existing
     translations, adds missing ones as empty strings)

Run after editing keys.json:
    python scripts/gen_lang.py
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LANG = os.path.join(ROOT, 'app', 'lang')
KEYS_FILE = os.path.join(LANG, 'keys.json')
HEADER = os.path.join(ROOT, 'src', 'lang_keys.h')
LANGS = ('es', 'en', 'pt')


def main():
    with open(KEYS_FILE, encoding='utf-8') as f:
        keys = json.load(f)
    if not isinstance(keys, list) or not keys:
        sys.exit('keys.json must be a non-empty JSON array of key names')
    if len(keys) != len(set(keys)):
        sys.exit('duplicate keys in keys.json')
    for key in keys:
        if not isinstance(key, str) or not key.startswith('S_'):
            sys.exit('invalid key: %r' % key)

    lines = [
        '/* GENERATED by scripts/gen_lang.py from app/lang/keys.json.',
        ' * Do not edit by hand. Include only from overlay_ui.c. */',
        '#ifndef OVERLAY_LANG_KEYS_H',
        '#define OVERLAY_LANG_KEYS_H',
        '',
        'enum {',
    ]
    for i in range(0, len(keys), 4):
        lines.append('    ' + ', '.join(keys[i:i + 4]) + ',')
    lines += [
        '    S_COUNT',
        '};',
        '',
        'static const char *const g_tr_keys[S_COUNT] = {',
    ]
    for i in range(0, len(keys), 4):
        lines.append('    ' + ', '.join('"%s"' % k for k in keys[i:i + 4]) + ',')
    lines += ['};', '', '#endif', '']
    with open(HEADER, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print('generated %s (%d keys)' % (HEADER, len(keys)))

    for code in LANGS:
        path = os.path.join(LANG, code + '.json')
        if os.path.exists(path):
            with open(path, encoding='utf-8') as f:
                data = json.load(f)
        else:
            data = {}
        added = 0
        for key in keys:
            if key not in data:
                data[key] = ''
                added += 1
        # Drop keys no longer in the canonical list.
        removed = [k for k in data if k not in keys]
        for k in removed:
            del data[k]
        ordered = {k: data[k] for k in keys}
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            json.dump(ordered, f, ensure_ascii=False, indent=2)
            f.write('\n')
        print('%s.json: %d keys (%d added, %d removed)' %
              (code, len(ordered), added, len(removed)))


if __name__ == '__main__':
    main()
